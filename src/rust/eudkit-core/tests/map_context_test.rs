use eudkit_core::{dts, symbols, CompilationConfig, CompilationSession};
use std::path::PathBuf;

fn repo_root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .unwrap()
        .parent()
        .unwrap()
        .parent()
        .unwrap()
        .to_path_buf()
}

#[test]
fn extracts_typed_map_context_from_real_scx_maps_with_zero_global_state() {
    let root = repo_root();
    let basemap_str = root.join("tests/outputmap/basemap/basemap.scx");
    assert!(basemap_str.exists(), "missing {:?}", basemap_str);
    let basemap_strx = root.join("tests/outputmap/basemap/basemap_strx.scx");
    let korean_map = root.join("tests/outputmap/basemap/사이비2.scx");

    let session_a = CompilationSession::from_map(&basemap_str, CompilationConfig::default())
        .expect("should load basemap.scx (legacy STR)");
    let session_b = CompilationSession::from_map(&basemap_strx, CompilationConfig::default())
        .expect("should load basemap_strx.scx (Remastered STRx)");
    let session_c = CompilationSession::from_map(&korean_map, CompilationConfig::default())
        .expect("should load Korean map fixture");

    let data_a = session_a.map_data();
    let data_b = session_b.map_data();
    let data_c = session_c.map_data();
    let canonical_a = session_a.canonical_symbols();
    let canonical_b = session_b.canonical_symbols();

    // Strings: 1-based string table extracted from STR and STRx
    assert!(!data_a.strings().is_empty(), "STR strings must be parsed");
    assert!(!data_b.strings().is_empty(), "STRx strings must be parsed");
    assert_eq!(
        data_a.strings().len(),
        data_b.strings().len(),
        "basemap.scx and basemap_strx.scx should have matching string counts"
    );

    // MRGN: 255 location slots, 1-based location IDs, "Anywhere" at location 64
    assert_eq!(data_a.locations().len(), 255);
    assert_eq!(
        symbols::location_id(data_a, canonical_a, "Anywhere"),
        Some(64)
    );
    assert_eq!(data_b.locations().len(), 255);
    assert_eq!(
        symbols::location_id(data_b, canonical_b, "Anywhere"),
        Some(64)
    );

    // UNIT: Placed units parsed into 36-byte records
    assert!(
        !data_a.placed_units().is_empty(),
        "basemap should have placed units"
    );
    assert_eq!(data_a.placed_units().len(), data_b.placed_units().len());

    // UPRP: 64 CUWP unit property slots (1-based 1..=64)
    assert_eq!(data_a.cuwp_slots().len(), 64);
    assert_eq!(data_a.cuwp_slots()[0].id, 1);
    assert_eq!(data_a.cuwp_slots()[63].id, 64);

    // UNIx: 228 extended unit settings (0..228) and unit name resolution
    assert_eq!(data_a.unit_settings().len(), 228);
    assert_eq!(
        symbols::unit_id(data_a, canonical_a, "Terran Marine"),
        Some(0)
    );
    assert_eq!(
        symbols::unit_id(data_a, canonical_a, "Zerg Zergling"),
        Some(37)
    );

    // SWNM: 256 switches (0..256)
    assert_eq!(data_a.switches().len(), 256);
    assert_eq!(symbols::switch_id(data_a, canonical_a, "Switch 1"), Some(0));
    assert_eq!(
        symbols::switch_id(data_a, canonical_a, "Switch 256"),
        Some(255)
    );

    // OWNR & SIDE: 12 player slots
    assert_eq!(data_a.players().len(), 12);
    assert!(
        data_a.players()[..8].iter().any(|p| p.owner != 0),
        "at least one player slot in P1..P8 must be active"
    );

    // TRIG: classic triggers extracted from Korean map fixture
    assert!(
        !data_c.triggers().is_empty() || data_a.triggers().is_empty(),
        "TRIG section parsed cleanly"
    );

    // TypeScript .d.ts Map Context Codegen
    let dts = dts::generate_dts(data_a, canonical_a, "basemap");
    assert!(dts.contains("// Generated by eudkit for basemap"));
    assert!(dts.contains("export type LocationId ="));
    assert!(dts.contains("\"Anywhere\""));
    assert!(dts.contains("export type UnitId ="));
    assert!(dts.contains("\"Terran Marine\""));
    assert!(dts.contains("\"Zerg Zergling\""));
    assert!(dts.contains("export type SwitchId ="));
    assert!(dts.contains("\"Switch 1\""));
    assert!(dts.contains("export type PlayerId ="));
    assert!(dts.contains("\"P1\""));
    assert!(dts.contains("\"CurrentPlayer\""));
    assert!(dts.contains("\"AllPlayers\""));
    assert!(dts.contains("export type StringId = number;"));
    assert!(dts.contains("export interface MapContext"));
    assert!(dts.contains("export declare const mapContext: MapContext;"));
    assert!(dts.contains("export const Locations ="));
    assert!(dts.contains("export const Units ="));
    assert!(dts.contains("export const Switches ="));
    assert!(dts.contains("export const Players ="));
}
